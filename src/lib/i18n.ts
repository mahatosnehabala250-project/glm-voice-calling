export function t(key: string, lang?: Language): string {
  const language = lang || (typeof window !== 'undefined'
    ? (localStorage.getItem('voiceai-lang') as Language) || 'en'
    : 'en');
  return translations[language]?.[key] || translations.en[key] || key;
}

export function getLanguage(): Language {
  if (typeof window === 'undefined') return 'en';
  return (localStorage.getItem('voiceai-lang') as Language) || 'en';
}

export function setLanguage(lang: Language): void {
  if (typeof window === 'undefined') return;
  localStorage.setItem('voiceai-lang', lang);
  window.dispatchEvent(new CustomEvent('voiceai-lang-change', { detail: lang }));
}
